// Generates src/styles/font-fallbacks.css: size-adjusted local fallback faces so the
// webfont swap causes no layout shift (reference.md §3.2).
//
// Why a script instead of fontaine's Vite plugin: the plugin emitted duplicate faces
// with conflicting metrics for the same family/style, and Chrome picked the wrong one
// (measured: body text reflowed by a full line). Here every fallback gets its own
// family name, so the browser simply skips any font that isn't installed.
//
// Run after changing fonts:  pnpm fonts:fallbacks
import { writeFile } from 'node:fs/promises'
import { createRequire } from 'node:module'
import { pathToFileURL } from 'node:url'
import { generateFontFace, getMetricsForFamily, readMetrics } from 'fontaine'

const require = createRequire(import.meta.url)
const file = (spec) => pathToFileURL(require.resolve(spec))

// [webfont file, style, fallback family name, local font, local() face name]
const faces = [
  ['@fontsource-variable/newsreader/files/newsreader-latin-opsz-normal.woff2', 'normal', 'Newsreader fb Georgia', 'Georgia', 'Georgia'],
  ['@fontsource-variable/newsreader/files/newsreader-latin-opsz-italic.woff2', 'italic', 'Newsreader fb Georgia', 'Georgia', 'Georgia Italic'],
  ['@fontsource-variable/newsreader/files/newsreader-latin-opsz-normal.woff2', 'normal', 'Newsreader fb Noto Serif', 'Noto Serif', 'Noto Serif'],
  ['@fontsource-variable/newsreader/files/newsreader-latin-opsz-italic.woff2', 'italic', 'Newsreader fb Noto Serif', 'Noto Serif', 'Noto Serif Italic'],
  ['@fontsource-variable/inter/files/inter-latin-wght-normal.woff2', 'normal', 'Inter fb Arial', 'Arial', 'Arial'],
  ['@fontsource-variable/inter/files/inter-latin-wght-normal.woff2', 'normal', 'Inter fb Roboto', 'Roboto', 'Roboto'],
]

let css = '/* GENERATED by scripts/generate-font-fallbacks.mjs — do not edit by hand. */\n'
for (const [webfont, style, family, local, localFace] of faces) {
  const metrics = await readMetrics(file(webfont))
  const fallbackMetrics = await getMetricsForFamily(local)
  if (!metrics || !fallbackMetrics) throw new Error(`Missing metrics for ${webfont} or ${local}`)
  css += generateFontFace(metrics, { name: family, font: localFace, metrics: fallbackMetrics, 'font-style': style })
}

await writeFile(new URL('../src/styles/font-fallbacks.css', import.meta.url), css)
console.log(css)
